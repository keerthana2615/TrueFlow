import { writeFileSync } from 'node:fs'
import { DEMO_SONGS } from '../src/data/demoSongs.js'

const q = (v) => `'${String(v).replace(/'/g, "''")}'`
const rows = DEMO_SONGS.map(
  (s) =>
    `  (${q(s.id)}, ${q(s.title)}, ${q(s.artist)}, ${q(s.album)}, ${q(s.genre)}, ${q(s.cover_url)}, ${q(s.audio_url)}, ${s.duration}, ${q(s.created_at)})`
).join(',\n')

const sql = `-- TuneFlow demo songs (generated by: npm run seed)
insert into public.songs (id, title, artist, album, genre, cover_url, audio_url, duration, created_at) values
${rows}
on conflict (id) do nothing;
`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`Wrote supabase/seed.sql with ${DEMO_SONGS.length} songs`)
